// Helpers shared by generators.
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
export const repoPath = (...p) => path.join(REPO, ...p);
export const readText = (rel) => readFileSync(repoPath(rel), 'utf8');

/** Escape a value for a Markdown table cell. */
export const cell = (v) => (v == null || v === '' ? '' : String(v).replace(/\|/g, '\\|').replace(/\r?\n/g, ' '));
export const code = (v) => (v == null || v === '' ? '' : '`' + String(v).replace(/`/g, "'").replace(/\|/g, '\\|') + '`');

/** A Markdown table from column headers and row arrays. */
export function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((r) => `| ${r.map((c) => (c == null ? '' : String(c))).join(' | ')} |`),
  ].join('\n');
}

/** Standard header for a generated page. `sources` are repo-relative paths. */
export function page({ title, description, sources = [], order, body }) {
  const fm = ['---', `description: ${JSON.stringify(description)}`, 'status: generated'];
  if (order != null) fm.push('sidebar:', `  order: ${order}`);
  if (sources.length) fm.push('sources:', ...sources.map((s) => `  - ${s}`));
  fm.push('---', '');
  // The H1 must be the first node: the site drops a leading H1 (it renders the title itself).
  return `${fm.join('\n')}\n# ${title}\n\n<!-- GENERATED by docs-site/scripts/gen. Do not edit; run \`npm run gen\` in docs-site/. -->\n\n${body.trim()}\n`;
}
